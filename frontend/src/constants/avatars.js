export const getDefaultAvatar = (identifier = 'akatsuki') => {
  // Deterministically map identifier to one of the 10 members
  let hash = 0;
  for (let i = 0; i < identifier.length; i++) {
    hash = (hash << 5) - hash + identifier.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % AKATSUKI_AVATARS.length;
  return AKATSUKI_AVATARS[index];
};
